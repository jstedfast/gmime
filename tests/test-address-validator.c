static void
collect_issue (const GMimeComplianceIssue *issue, gpointer user_data)
{
	GArray *issues = user_data;
	g_array_append_val (issues, *issue);
}

static void
append_issue (const GMimeComplianceIssue *issue, gpointer user_data)
{
	GString *output = user_data;

	g_string_append_printf (output, "%s%d:%" G_GINT64_FORMAT ":%" G_GUINT64_FORMAT
		":%" G_GUINT64_FORMAT ":%d:%d", output->len ? "," : "", issue->violation,
		issue->stream_offset, issue->line_number, issue->column_number,
		issue->position_kind, issue->context);
}

