G_LOCK_DEFINE_STATIC (mime_types);
static GHashTable *mime_types;
static GHashTable *extensions;

static void
ensure_initialized (void)
{
	guint i;

	if (mime_types)
		return;

	mime_types = g_hash_table_new_full (g_mime_strcase_hash, g_mime_strcase_equal, g_free, g_free);
	extensions = g_hash_table_new_full (g_mime_strcase_hash, g_mime_strcase_equal, g_free, g_free);

	for (i = 0; i < G_N_ELEMENTS (builtin_mime_types); i++)
		g_hash_table_insert (mime_types, g_strdup (builtin_mime_types[i].key), g_strdup (builtin_mime_types[i].value));

	for (i = 0; i < G_N_ELEMENTS (builtin_extensions); i++)
		g_hash_table_insert (extensions, g_strdup (builtin_extensions[i].key), g_strdup (builtin_extensions[i].value));
}

static const char *
get_extension (const char *file_name)
{
	const char *end = file_name + strlen (file_name);
	const char *p = end;

	while (p > file_name) {
		p--;

		if (*p == '.')
			return p + 1 == end ? end : p;

		if (G_IS_DIR_SEPARATOR (*p))
			break;
	}

	return end;
}

/**
 * g_mime_types_get_mime_type:
 * @file_name: (type filename): a file name or path
 *
 * Gets the MIME-type based on the last extension of @file_name, without
 * accessing the file or inspecting its content. Directory separators follow
 * the host platform. Empty names, extensionless names, trailing dots, and
 * unknown extensions use application/octet-stream.
 *
 * Returns: (transfer full): the MIME-type; free with g_free().
 **/
char *
g_mime_types_get_mime_type (const char *file_name)
{
	const char *value;
	char *result;

	g_return_val_if_fail (file_name != NULL, NULL);

	G_LOCK (mime_types);
	ensure_initialized ();
	value = g_hash_table_lookup (mime_types, get_extension (file_name));
	result = g_strdup (value ? value : "application/octet-stream");
	G_UNLOCK (mime_types);

	return result;
}

/**
 * g_mime_types_try_get_extension:
 * @mime_type: a MIME-type, without parameters or surrounding whitespace
 * @extension: (out) (transfer full) (nullable): the preferred extension,
 * including its leading dot, or %NULL if unknown
 *
 * Looks up the exact MIME-type, ignoring ASCII case. Does not parse or
 * normalize a Content-Type value. An empty or unknown MIME-type is not found.
 *
 * Returns: %TRUE if the MIME-type has a preferred extension.
 **/
gboolean
g_mime_types_try_get_extension (const char *mime_type, char **extension)
{
	g_return_val_if_fail (mime_type != NULL, FALSE);
	g_return_val_if_fail (extension != NULL, FALSE);

	G_LOCK (mime_types);
	ensure_initialized ();
	*extension = g_strdup (g_hash_table_lookup (extensions, mime_type));
	G_UNLOCK (mime_types);

	return *extension != NULL;
}

/**
 * g_mime_types_register:
 * @mime_type: a nonempty MIME-type
 * @extension: a nonempty file extension, with or without a leading dot
 *
 * Registers both directions of a mapping, replacing any existing entry for
 * this extension and any preferred extension for this MIME-type. Other
 * mappings, including old aliases, remain unchanged. A leading dot is
 * prepended if absent. Values are copied as supplied, without trimming,
 * validation of MIME syntax, or case normalization.
 *
 * The two updates are atomic with respect to other registry operations.
 **/
void
g_mime_types_register (const char *mime_type, const char *extension)
{
	char *dotted;

	g_return_if_fail (mime_type != NULL && *mime_type != '\0');
	g_return_if_fail (extension != NULL && *extension != '\0');

	dotted = *extension == '.' ? g_strdup (extension) : g_strconcat (".", extension, NULL);

	G_LOCK (mime_types);
	ensure_initialized ();
	g_hash_table_replace (mime_types, g_strdup (dotted), g_strdup (mime_type));
	g_hash_table_replace (extensions, g_strdup (mime_type), dotted);
	G_UNLOCK (mime_types);
}
