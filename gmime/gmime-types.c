/**
 * SECTION: gmime-types
 * @title: MIME Types
 * @short_description: File extension and MIME-type mappings
 *
 * Maps file extensions to MIME-types and MIME-types to preferred extensions,
 * using MimeKit's built-in mappings rather than the host's MIME database.
 * The two directions are independent: a type can have several extensions,
 * and a preferred extension can be shared by aliases of a type.
 *
 * Registrations are process-wide and survive g_mime_shutdown(). Lookups
 * and registrations are synchronized, and returned strings are owned copies
 * that remain valid after later registrations. Comparisons use ASCII
 * case-insensitivity, as elsewhere in GMime's MIME-type handling.
 **/

